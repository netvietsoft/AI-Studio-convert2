/**
 * Canonical Registry of 12 Face/Beauty Modules and 104 Audited Features
 * with Testability Classification and Gate 5 Evidence Levels according to TASK_009 standard.
 *
 * Evidence Levels:
 * - LEVEL_A: Metadata and interface contract verified
 * - LEVEL_B: Production Kotlin dispatch and parameter normalization verified
 * - LEVEL_C: JNI binding entry point invoked
 * - LEVEL_D: Real C++ native engine executed
 * - LEVEL_E: Real output buffer/pixel/landmark invariant verified
 * - LEVEL_F: Not host-automatable / requires physical device (Gate 6) or visual QA (Gate 7)
 */
enum class TestabilityClass(
    val code: String,
    val description: String
) {
    CLASS_A_PARAMETER_CLAMPING_AND_TRANSFORM("CLASS_A", "Parameter Transformation & Boundary Clamping"),
    CLASS_B_LANDMARK_AND_GEOMETRIC_BOUNDS("CLASS_B", "Landmark & ROI Geometric Bounds Validation"),
    CLASS_C_DISCRETE_PRESET_AND_COLOR_PALETTE("CLASS_C", "Color LUT / Palette & Discrete Preset Selection"),
    CLASS_D_UNCHANGED_REGION_AND_ROI_PRESERVATION("CLASS_D", "Unchanged-Region & Alpha Matte Mask Boundaries"),
    CLASS_E_PIPELINE_CONTRACT_AND_CRASH_SAFETY("CLASS_E", "End-to-End Pipeline & Native Crash Safety Contracts")
}

enum class Gate5EvidenceLevel(
    val code: String,
    val description: String
) {
    LEVEL_A_METADATA_CONTRACT("LEVEL_A", "Metadata & Interface Contract Verified"),
    LEVEL_B_KOTLIN_DISPATCH("LEVEL_B", "Production Kotlin Dispatch & Parameter Normalization Verified"),
    LEVEL_C_JNI_BINDING("LEVEL_C", "JNI Native Binding Invoked"),
    LEVEL_D_REAL_NATIVE_ENGINE("LEVEL_D", "Real C++ Native Engine Executed"),
    LEVEL_E_OUTPUT_INVARIANT("LEVEL_E", "Real Output Buffer / Pixel / Landmark Invariant Verified"),
    LEVEL_F_DEVICE_OR_VISUAL_REQUIRED("LEVEL_F", "Not Host-Automatable / Requires Physical Device (Gate 6) or Visual QA (Gate 7)")
}

